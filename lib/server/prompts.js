function writerNote(artist) {
  const w = WRITERS[artist];
  return `핵심 정서: ${w.core}
자아: ${w.self}
성격: ${w.character}
시선: ${w.gaze}
역할: ${w.role}
말투:
${w.tone.map((m) => "- " + m).join("\n")}
이 사람의 눈과 말투를 빌려 쓰되, 말하는 쪽은 다락방이다. 이 사람이 되어 관객에게 말을 걸지 않고, 평가하거나 위로하거나 조언하지 않는다.`;
}

