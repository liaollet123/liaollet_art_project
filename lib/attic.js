/** 고른 감정을 앞세우고, 글에서 읽은 키워드와 아티스트의 결을 뒤에 붙인다. */
export function suggestTags(text, artist, emotion) {
  const fromEmotion = EMOTION_TAGS[emotion] || (emotion ? ["#" + emotion.replace(/\s/g, "")] : []);
  const hit = DICT.filter(([r]) => r.test(text)).map(([, t]) => t);
  return Array.from(new Set([...fromEmotion, ...hit, ...BASE[artist], "#감정의다락방"])).slice(0, 7);
}

/**
 * 한국어 조사 붙이기 — 앞 글자의 받침에 따라 고른다.
 * 관객이 감정을 직접 써 넣을 수 있으므로 자동으로 맞춘다.
 * withParticle("레이어") → "레이어와", withParticle("여백") → "여백과"
 */
export function withParticle(word, withJong = "과", withoutJong = "와") {
  const s = String(word || "");
  if (!s) return s;
  const code = s.charCodeAt(s.length - 1);
  const isHangul = code >= 0xac00 && code <= 0xd7a3;
  if (!isHangul) return s + withoutJong;
  return s + ((code - 0xac00) % 28 !== 0 ? withJong : withoutJong);
}
