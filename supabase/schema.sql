-- Supabase 대시보드 > SQL Editor 에 통째로 붙여 넣고 한 번 실행한다.
-- 모든 읽기·쓰기는 서버(app/api)가 service role 키로만 한다. 브라우저는 DB에 직접 닿지 않는다.

create table if not exists day_seq (
  day text primary key,          -- 순번을 세는 열쇠. 'all' 하나(전시 전체 누적 순번)
  seq int not null default 0
);

-- 작품 번호. 6장에서 엮을 때 한 줄씩 생긴다(입장할 때가 아니다)
create table if not exists tickets (
  no text primary key,           -- YYMMDD + 전시 전체 누적 순번 (예: 2610231)
  day text not null,             -- YYMMDD (한국 시간). 하루 기회 수를 센다
  seq int not null,
  device_id text,                -- 서명된 쿠키로 구별한 기기
  signature text,                -- 1장에서 적은 오늘의 창작자 이름 = 아이디 = 서명. 처음 쓴 기기의 것
  created_at timestamptz not null default now()
);
-- 이미 만든 표에도 칸을 더한다(여러 번 실행해도 안전)
alter table tickets add column if not exists device_id text;
alter table tickets add column if not exists signature text;
-- 한 사람에 하루 세 번이라 (기기, 날짜) 고유 제약은 두지 않는다. 기기별·아이디별 조회만 빠르게
drop index if exists tickets_one_per_device_day;
drop index if exists tickets_device;
create index if not exists tickets_device_day on tickets (device_id, day);
create index if not exists tickets_signature on tickets (lower(signature));

-- 작품. 저장하는 칸은 아홉 개뿐이다. 사진과 콜라주는 Cloudinary에 올리고 주소(URL)만 남긴다.
create table if not exists liaollet (
  id bigint generated by default as identity primary key,  -- 추가된 순서
  ticket bigint not null unique,                           -- p.06 엮을 때 매긴 작품 번호. 번호 하나에 작품 한 장
  artist varchar not null,                                 -- p.04 LIA / OL / LET
  source text[] not null default '{}',                     -- p.06 올린 사진 주소들
  collage text not null,                                   -- p.07 콜라주 주소
  story text,                                              -- p.06 오늘의 이야기
  tags text[],                                             -- p.06 활성화된 태그
  signature text,                                          -- p.01 오늘의 창작자 이름(아이디). 작품의 서명이 되고 1장에서 이 이름으로 찾는다
  likes int not null default 0,                            -- p.08 공감 수
  created_at timestamptz not null default now()
);
create index if not exists liaollet_created on liaollet (created_at desc, id desc);
create index if not exists liaollet_signature on liaollet (lower(signature));

create table if not exists usage (
  k text primary key,            -- 예: compose:기기ID, ip:1.2.3.4
  n int not null default 0,
  reset_at timestamptz not null
);

-- 브라우저용 anon 키로는 아무것도 못 하게 잠근다. 서버의 service role 키는 RLS를 건너뛴다
alter table day_seq enable row level security;
alter table tickets enable row level security;
alter table liaollet enable row level security;
alter table usage enable row level security;

-- 두 사람이 동시에 서명해도 번호가 겹치지 않게 한 줄로 올린다. 서버는 p_day 에 'all' 을 넘겨 전시 전체 누적 순번을 센다(= 엮인 작품 수)
create or replace function next_ticket(p_day text) returns int
language sql as $$
  insert into day_seq (day, seq) values (p_day, 1)
  on conflict (day) do update set seq = day_seq.seq + 1
  returning seq;
$$;

-- 창(window) 안에서 p_limit 번까지만 true. LLM 비용이 새지 않게 막는 계수기
create or replace function hit_usage(p_key text, p_limit int, p_window int) returns boolean
language plpgsql as $$
declare cur usage%rowtype;
begin
  insert into usage (k, n, reset_at) values (p_key, 0, now() + make_interval(secs => p_window))
  on conflict (k) do update set
    n = case when usage.reset_at < now() then 0 else usage.n end,
    reset_at = case when usage.reset_at < now() then now() + make_interval(secs => p_window) else usage.reset_at end
  returning * into cur;
  if cur.n >= p_limit then return false; end if;
  update usage set n = n + 1 where k = p_key;
  return true;
end;
$$;

-- 공감 누르기/빼기. 두 사람이 동시에 눌러도 수가 엇갈리지 않게 DB에서 한 번에 올린다
create or replace function like_work(p_id bigint, p_delta int) returns int
language sql as $$
  update liaollet set likes = greatest(0, likes + p_delta) where id = p_id returning likes;
$$;

-- 누가 어느 작품에 공감했는지. 브라우저의 기억만 믿으면 버튼을 빠르게 연타했을 때 수가 계속 올라가서,
-- (작품, 기기) 한 쌍에 한 줄만 두고 줄이 실제로 생기거나 지워질 때만 likes 를 움직인다
create table if not exists work_likes (
  work_id bigint not null references liaollet (id) on delete cascade,
  device_id text not null,
  created_at timestamptz not null default now(),
  primary key (work_id, device_id)
);
alter table work_likes enable row level security;

-- 같은 요청이 몇 번 와도 결과가 같다. 이미 공감한 기기가 또 누르면 아무것도 바뀌지 않는다
create or replace function set_like(p_id bigint, p_device text, p_on boolean) returns int
language plpgsql as $$
declare changed int;
declare cur int;
begin
  if not exists (select 1 from liaollet where id = p_id) then return null; end if;
  if p_on then
    insert into work_likes (work_id, device_id) values (p_id, p_device) on conflict do nothing;
  else
    delete from work_likes where work_id = p_id and device_id = p_device;
  end if;
  get diagnostics changed = row_count;
  update liaollet set likes = greatest(0, likes + case when p_on then changed else -changed end)
    where id = p_id returning likes into cur;
  return cur;
end;
$$;

