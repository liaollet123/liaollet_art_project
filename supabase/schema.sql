-- 감정의 다락방 — Supabase 스키마
-- (예전 works / notes 표를 만들어 두었다면 먼저: drop table if exists notes, works; drop function if exists like_work(text, int);)
-- Supabase 대시보드 > SQL Editor 에 통째로 붙여 넣고 한 번 실행한다.
-- 모든 읽기·쓰기는 서버(app/api)가 service role 키로만 한다. 브라우저는 DB에 직접 닿지 않는다.

create table if not exists day_seq (
  day text primary key,          -- MMDD (한국 시간)
  seq int not null default 0
);

create table if not exists tickets (
  no text primary key,           -- MMDD + 그날의 순번
  day text not null,
  seq int not null,
  device_id text,                -- 서명된 쿠키로 구별한 기기. 한 사람(기기)에 하루 한 장
  created_at timestamptz not null default now()
);
-- 이미 만든 표에도 칸을 더한다(여러 번 실행해도 안전)
alter table tickets add column if not exists device_id text;
create unique index if not exists tickets_one_per_device_day on tickets (device_id, day);

-- 작품. 저장하는 칸은 아홉 개뿐이다. 사진과 콜라주는 Cloudinary에 올리고 주소(URL)만 남긴다.
create table if not exists liaollet (
  id bigint generated by default as identity primary key,  -- 추가된 순서
  ticket bigint not null unique,                           -- p.01 창작 에디션 티켓 번호. 티켓 하나에 작품 한 장
  artist varchar not null,                                 -- p.04 LIA / OL / LET
  source text[] not null default '{}',                     -- p.06 올린 사진 주소들
  collage text not null,                                   -- p.07 콜라주 주소
  story text,                                              -- p.06 오늘의 이야기
  tags text[],                                             -- p.06 활성화된 태그
  signature text,                                          -- p.07 서명
  likes int not null default 0,                            -- p.08 공감 수
  created_at timestamptz not null default now()
);
create index if not exists liaollet_created on liaollet (created_at desc, id desc);

create table if not exists usage (
  k text primary key,            -- 예: compose:102101, ip:1.2.3.4
  n int not null default 0,
  reset_at timestamptz not null
);

-- 브라우저용 anon 키로는 아무것도 못 하게 잠근다. 서버의 service role 키는 RLS를 건너뛴다
alter table day_seq enable row level security;
alter table tickets enable row level security;
alter table liaollet enable row level security;
alter table usage enable row level security;

-- 두 사람이 동시에 티켓을 받아도 번호가 겹치지 않게 한 줄로 올린다
create or replace function next_ticket(p_day text) returns int
language sql as $$
  insert into day_seq (day, seq) values (p_day, 1)
  on conflict (day) do update set seq = day_seq.seq + 1
  returning seq;
$$;

-- 창(window) 안에서 p_limit 번까지만 true. LLM 비용이 새지 않게 막는 계수기
create or replace function hit_usage(p_key text, p_limit int, p_window int) returns boolean
language plpgsql as $$
declare cur usage%rowtype;
begin
  insert into usage (k, n, reset_at) values (p_key, 0, now() + make_interval(secs => p_window))
  on conflict (k) do update set
    n = case when usage.reset_at < now() then 0 else usage.n end,
    reset_at = case when usage.reset_at < now() then now() + make_interval(secs => p_window) else usage.reset_at end
  returning * into cur;
  if cur.n >= p_limit then return false; end if;
  update usage set n = n + 1 where k = p_key;
  return true;
end;
$$;

-- 공감 누르기/빼기. 두 사람이 동시에 눌러도 수가 엇갈리지 않게 DB에서 한 번에 올린다
create or replace function like_work(p_id bigint, p_delta int) returns int
language sql as $$
  update liaollet set likes = greatest(0, likes + p_delta) where id = p_id returning likes;
$$;

